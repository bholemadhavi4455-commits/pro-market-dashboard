/**
 * Property-based tests for Listing data validation
 * 
 * **Validates: Requirements 4.1, 6.1**
 * 
 * This test suite implements Property 1: UI Rendering Completeness from the design document.
 * It verifies that any generated Listing object contains all required fields for UI rendering:
 * - product name
 * - source name
 * - price (with currency symbol)
 * - star rating (numeric value to one decimal place)
 * - review count
 * 
 * Property-based testing ensures these validation rules hold across all possible
 * valid Listing objects, not just hand-picked examples.
 */

import * as fc from 'fast-check';
import { arbListing, pbtConfig } from './generators';
import { Listing } from '../models';

describe('Property 1: UI Rendering Completeness', () => {
  /**
   * Property Test: All required Listing fields are present and valid
   * 
   * **Validates: Requirements 4.1, 6.1**
   * 
   * For any Listing object generated by our arbitrary, when that Listing
   * would be rendered as a PriceCard component, all required fields must be:
   * 1. Present (not undefined/null)
   * 2. Valid according to their type and constraint specifications
   * 3. Suitable for UI rendering without additional transformation
   * 
   * This property ensures the data contract between backend and frontend
   * is maintained, preventing runtime errors in the UI layer.
   */
  test('Any Listing contains all required fields for UI rendering', () => {
    fc.assert(
      fc.property(arbListing(), (listing: Listing) => {
        // ===== FIELD PRESENCE CHECKS =====
        // All fields required for PriceCard rendering must exist
        
        expect(listing).toHaveProperty('productName');
        expect(listing).toHaveProperty('source');
        expect(listing).toHaveProperty('price');
        expect(listing).toHaveProperty('currency');
        expect(listing).toHaveProperty('rating');
        expect(listing).toHaveProperty('reviewCount');
        
        // ===== PRODUCT NAME VALIDATION =====
        // Must be non-empty string (max 200 chars per design spec)
        expect(typeof listing.productName).toBe('string');
        expect(listing.productName.length).toBeGreaterThan(0);
        expect(listing.productName.length).toBeLessThanOrEqual(200);
        
        // ===== SOURCE NAME VALIDATION =====
        // Must be non-empty string identifying the marketplace/retailer
        expect(typeof listing.source).toBe('string');
        expect(listing.source.length).toBeGreaterThan(0);
        
        // ===== PRICE VALIDATION =====
        // Price must be positive integer (smallest currency unit: cents/paise)
        expect(typeof listing.price).toBe('number');
        expect(Number.isInteger(listing.price)).toBe(true);
        expect(listing.price).toBeGreaterThan(0);
        
        // ===== CURRENCY VALIDATION =====
        // Must be valid ISO 4217 currency code (3 uppercase letters)
        expect(typeof listing.currency).toBe('string');
        expect(listing.currency).toMatch(/^[A-Z]{3}$/);
        expect(['USD', 'INR', 'EUR', 'GBP', 'JPY']).toContain(listing.currency);
        
        // ===== STAR RATING VALIDATION =====
        // Must be numeric value in range [0.0, 5.0] with one decimal precision
        expect(typeof listing.rating).toBe('number');
        expect(listing.rating).toBeGreaterThanOrEqual(0.0);
        expect(listing.rating).toBeLessThanOrEqual(5.0);
        
        // Verify one decimal precision (requirement for UI rendering)
        const ratingStr = listing.rating.toString();
        const decimalPart = ratingStr.split('.')[1];
        if (decimalPart) {
          expect(decimalPart.length).toBeLessThanOrEqual(1);
        }
        
        // ===== REVIEW COUNT VALIDATION =====
        // Must be non-negative integer
        expect(typeof listing.reviewCount).toBe('number');
        expect(Number.isInteger(listing.reviewCount)).toBe(true);
        expect(listing.reviewCount).toBeGreaterThanOrEqual(0);
        
        // ===== ADDITIONAL INTEGRITY CHECKS =====
        // These fields are not directly displayed in basic PriceCard but are
        // required for the full data model and extended functionality
        
        // ID must follow format: "{source}_{productId}"
        expect(listing.id).toBeTruthy();
        expect(listing.id).toContain('_');
        
        // Category must be one of the predefined valid categories
        expect(['Electronics', 'Books', 'Clothing', 'Home & Kitchen', 'Sports']).toContain(
          listing.category
        );
        
        // CompositeScore must be in valid range [0, 100]
        expect(listing.compositeScore).toBeGreaterThanOrEqual(0);
        expect(listing.compositeScore).toBeLessThanOrEqual(100);
        
        // FetchedAt must be valid ISO 8601 timestamp
        expect(listing.fetchedAt).toBeTruthy();
        expect(() => new Date(listing.fetchedAt)).not.toThrow();
        expect(new Date(listing.fetchedAt).toISOString()).toBe(listing.fetchedAt);
        
        // SourceUrl must be valid URL string
        expect(listing.sourceUrl).toBeTruthy();
        expect(() => new URL(listing.sourceUrl)).not.toThrow();
      }),
      {
        ...pbtConfig,
        numRuns: 100, // Minimum 100 iterations as per requirements
      }
    );
  });

  /**
   * Property Test: Price with currency symbol can be formatted for display
   * 
   * **Validates: Requirements 4.1**
   * 
   * This test ensures that the price and currency fields can be successfully
   * combined to create a displayable price string with currency symbol.
   * This is a critical UI rendering requirement.
   */
  test('Price and currency can be formatted for UI display', () => {
    fc.assert(
      fc.property(arbListing(), (listing: Listing) => {
        // Simulate UI formatting logic: convert smallest unit to major unit
        const majorUnitPrice = listing.price / 100;
        
        // Basic currency symbol mapping (as would be done in UI)
        const currencySymbols: { [key: string]: string } = {
          'USD': '$',
          'INR': '₹',
          'EUR': '€',
          'GBP': '£',
          'JPY': '¥',
        };
        
        const symbol = currencySymbols[listing.currency];
        expect(symbol).toBeDefined();
        
        // Format price string (e.g., "$249.99" or "₹24,999.00")
        const formattedPrice = `${symbol}${majorUnitPrice.toFixed(2)}`;
        
        // Verify the formatted price is a valid string
        expect(typeof formattedPrice).toBe('string');
        expect(formattedPrice.length).toBeGreaterThan(1); // At least symbol + digit
        expect(formattedPrice).toContain(symbol);
      }),
      {
        ...pbtConfig,
        numRuns: 100,
      }
    );
  });

  /**
   * Property Test: Rating value supports visual star rendering
   * 
   * **Validates: Requirements 6.4**
   * 
   * The rating must be suitable for rendering as a 5-star visual scale.
   * This test verifies that the rating can be decomposed into full stars,
   * half stars, and empty stars totaling exactly 5 stars.
   */
  test('Rating value can be converted to visual star representation', () => {
    fc.assert(
      fc.property(arbListing(), (listing: Listing) => {
        const rating = listing.rating;
        
        // Calculate star breakdown (as would be done in UI)
        const fullStars = Math.floor(rating);
        const hasHalfStar = (rating % 1) >= 0.5;
        const emptyStars = 5 - fullStars - (hasHalfStar ? 1 : 0);
        
        // Verify star calculation is valid
        expect(fullStars).toBeGreaterThanOrEqual(0);
        expect(fullStars).toBeLessThanOrEqual(5);
        expect(emptyStars).toBeGreaterThanOrEqual(0);
        expect(emptyStars).toBeLessThanOrEqual(5);
        
        // Total stars must always equal 5
        const totalStars = fullStars + (hasHalfStar ? 1 : 0) + emptyStars;
        expect(totalStars).toBe(5);
        
        // Verify we can create a star string representation
        const starString = '★'.repeat(fullStars) + 
                          (hasHalfStar ? '⯨' : '') + 
                          '☆'.repeat(emptyStars);
        expect(starString.length).toBeGreaterThanOrEqual(5);
      }),
      {
        ...pbtConfig,
        numRuns: 100,
      }
    );
  });

  /**
   * Property Test: Review count displays as readable number
   * 
   * **Validates: Requirements 6.1**
   * 
   * The review count must be displayable as a human-readable number string,
   * potentially with formatting for large numbers (e.g., "1,203" or "50K").
   */
  test('Review count can be formatted as readable number string', () => {
    fc.assert(
      fc.property(arbListing(), (listing: Listing) => {
        const reviewCount = listing.reviewCount;
        
        // Simulate UI number formatting
        let displayCount: string;
        if (reviewCount >= 1000) {
          // Format as "1.2K" for thousands
          displayCount = `${(reviewCount / 1000).toFixed(1)}K`;
        } else {
          // Format with comma separators
          displayCount = reviewCount.toLocaleString();
        }
        
        // Verify formatted count is valid
        expect(typeof displayCount).toBe('string');
        expect(displayCount.length).toBeGreaterThan(0);
        
        // Original count must be non-negative
        expect(reviewCount).toBeGreaterThanOrEqual(0);
      }),
      {
        ...pbtConfig,
        numRuns: 100,
      }
    );
  });
});

